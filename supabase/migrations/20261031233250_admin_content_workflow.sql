ALTER TABLE public.total_posts
  ADD COLUMN IF NOT EXISTS is_draft boolean NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS public.post_revisions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id bigint NOT NULL,
  post_title text NOT NULL DEFAULT '',
  snapshot jsonb NOT NULL,
  action text NOT NULL DEFAULT 'update',
  changed_by text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS post_revisions_post_id_created_at_idx
  ON public.post_revisions (post_id, created_at DESC);

ALTER TABLE public.post_revisions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.post_revisions FROM PUBLIC, anon;
GRANT SELECT, INSERT ON public.post_revisions TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.post_revisions_id_seq TO authenticated;

DROP POLICY IF EXISTS "Authenticated admins can read post revisions" ON public.post_revisions;
CREATE POLICY "Authenticated admins can read post revisions"
  ON public.post_revisions FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS "Authenticated admins can insert post revisions" ON public.post_revisions;
CREATE POLICY "Authenticated admins can insert post revisions"
  ON public.post_revisions FOR INSERT TO authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "Authenticated users can list images bucket" ON storage.objects;
CREATE POLICY "Authenticated users can list images bucket"
  ON storage.objects FOR SELECT TO authenticated USING (bucket_id = 'images');
